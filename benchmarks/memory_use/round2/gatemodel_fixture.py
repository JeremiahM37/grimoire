"""Write go/internal/rerank/testdata/gate_reference.json: logits from the HF model for 20 synthetic
(request, memory) pairs, for the Go parity test. usage: gatemodel_fixture.py MODEL_DIR (venv python)"""
import sys, json, torch
from transformers import AutoTokenizer, AutoModelForSequenceClassification
P = [
 ("deploy the staging build to the kestrel host", "Deploys to kestrel always go through the blue/green script, never rsync directly."),
 ("rename the config module", "The user prefers tabs over spaces in Makefiles."),
 ("add a retry to the upload client", "Upload client retries must use jittered exponential backoff capped at 30 seconds."),
 ("what is for lunch", "Backups run nightly at 03:00 and are verified monthly."),
 ("write the release notes for 2.4", "Release notes are written in the past tense and list breaking changes first."),
 ("fix the flaky test in billing", "Billing tests must never hit the real payment sandbox; use the recorded fixtures."),
 ("bump the go version", "CI pins Go 1.22 until the vendored linter is updated."),
 ("summarise this pdf", "The user's cat is called Miso."),
 ("rotate the api keys", "API keys live in the secrets vault; never write them into the notes vault."),
 ("set up a new python project", "Use uv, not pip, for new Python projects."),
 ("tidy the readme", "README screenshots are regenerated by make docs, do not edit by hand."),
 ("run the migration on prod", "Production migrations need a snapshot first and a second person to approve."),
 ("draft an email to the landlord", "The landlord prefers phone calls to email."),
 ("why is the build slow", "The build cache lives on the bulk volume; if it is missing builds take 20 minutes."),
 ("open a pull request for this branch", "Commits must not carry a Co-Authored-By trailer."),
 ("explain the retry policy", "Upload client retries must use jittered exponential backoff capped at 30 seconds."),
 ("café menu für übermorgen", "Der Nutzer isst kein Fleisch und keinen Fisch."),
 ("   ", "An empty request still has to score without crashing."),
 ("remind me about the dentist " * 30, "The dentist appointment is on the 14th at 9:30 and needs a referral letter."),
 ("update the dashboard panel", "Dashboards are generated from work_repos.json; hand edits are overwritten. " * 8),
]
tok = AutoTokenizer.from_pretrained(sys.argv[1]); m = AutoModelForSequenceClassification.from_pretrained(sys.argv[1]).eval()
cases = []
for q, d in P:
    e = tok(q, d, truncation='longest_first', max_length=192, return_tensors='pt')
    with torch.no_grad(): s = m(**e).logits.item()
    cases.append(dict(query=q, doc=d, max_len=192, score=s))
json.dump(dict(cases=cases), open('go/internal/rerank/testdata/gate_reference.json', 'w'), indent=1, ensure_ascii=False)
print(len(cases))
